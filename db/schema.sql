-- ---------- Cardápio ----------

CREATE TABLE product_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  position SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES product_categories (id),
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
  image_url TEXT,
  available BOOLEAN NOT NULL DEFAULT TRUE,
  -- Produto especial do "Monte seu Lanche" (preço = base; o resto vem dos ingredientes).
  is_builder BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX products_single_builder ON products (is_builder) WHERE is_builder;
CREATE INDEX products_category_idx ON products (category_id);

-- Categorias de ingrediente e as regras do "Monte seu Lanche" (em unidades).
CREATE TABLE ingredient_categories (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  position SMALLINT NOT NULL DEFAULT 0,
  builder_min SMALLINT NOT NULL DEFAULT 0 CHECK (builder_min >= 0),
  builder_max SMALLINT NOT NULL DEFAULT 1 CHECK (builder_max >= builder_min),
  builder_max_per_item SMALLINT NOT NULL DEFAULT 1 CHECK (builder_max_per_item >= 1)
);

CREATE TABLE ingredients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_slug TEXT NOT NULL REFERENCES ingredient_categories (slug) ON UPDATE CASCADE,
  name TEXT NOT NULL UNIQUE,
  -- Preço de cada unidade a mais (no lanche pronto) ou escolhida no "Monte seu Lanche".
  price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  -- FALSE = acabou: todo lanche que leva o ingrediente sai do cardápio.
  in_stock BOOLEAN NOT NULL DEFAULT TRUE,
  available_as_extra BOOLEAN NOT NULL DEFAULT FALSE,
  available_in_builder BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Composição de cada lanche.
CREATE TABLE product_ingredients (
  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients (id) ON DELETE RESTRICT,
  quantity SMALLINT NOT NULL DEFAULT 1 CHECK (quantity >= 1),
  position SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (product_id, ingredient_id)
);

-- Adicionais que não fazem parte do lanche, mas ele aceita.
CREATE TABLE product_extras (
  product_id INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients (id) ON DELETE CASCADE,
  PRIMARY KEY (product_id, ingredient_id)
);

-- ---------- Clientes e cupons ----------

CREATE TABLE customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  -- DDD + número, só dígitos (sem +55).
  phone TEXT NOT NULL UNIQUE CHECK (phone ~ '^[0-9]{10,11}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE coupons (
  code TEXT PRIMARY KEY CHECK (code = upper(code)),
  description TEXT NOT NULL,
  discount_percent NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
  first_order_only BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  valid_until TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Pedidos ----------

CREATE TABLE orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER REFERENCES customers (id) ON DELETE SET NULL,
  -- Contato como informado no pedido (o cadastro do cliente pode mudar depois).
  customer_name TEXT NOT NULL,
  customer_phone TEXT,
  channel TEXT NOT NULL CHECK (channel IN ('website', 'balcao', 'delivery', 'whatsapp')),
  status TEXT NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'preparando', 'concluido', 'cancelado')),
  payment_method TEXT NOT NULL CHECK (payment_method IN ('Pix', 'Cartão', 'Dinheiro')),
  change_for TEXT, -- troco
  cep TEXT,
  address_street TEXT,
  address_number TEXT,
  address_complement TEXT,
  address_neighborhood TEXT,
  notes TEXT, -- observação do cliente
  subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  discount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
  total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
  coupon_code TEXT REFERENCES coupons (code) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (total = subtotal - discount)
);
CREATE INDEX orders_status_created_idx ON orders (status, created_at DESC);
CREATE INDEX orders_created_idx ON orders (created_at DESC);
CREATE INDEX orders_customer_idx ON orders (customer_id);

CREATE TABLE order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  -- Nome e preço congelados: apagar/renomear o produto não altera pedidos antigos.
  product_id INTEGER REFERENCES products (id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0), -- já inclui os adicionais
  notes TEXT
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

-- O que foi tirado/adicionado em cada item, com nome e preço congelados.
CREATE TABLE order_item_customizations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id INTEGER NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
  ingredient_id INTEGER REFERENCES ingredients (id) ON DELETE SET NULL,
  ingredient_name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('removed', 'added')),
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0)
);
CREATE INDEX order_item_customizations_item_idx ON order_item_customizations (order_item_id);

-- ---------- updated_at automático ----------

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER products_updated_at BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER ingredients_updated_at BEFORE UPDATE ON ingredients
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER orders_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
